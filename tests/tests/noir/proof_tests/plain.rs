fn plain_test<H: TranscriptHasher<TranscriptFieldType>>(
    proof_file: &str,
    vk_file: &str,
    vk_to_buffer: fn(&VerifyingKeyBarretenberg<Bn254G1>) -> Vec<u8>,
    circuit_file: &str,
    witness_file: &str,
    has_zk: ZeroKnowledge,
) {
    let constraint_system =
        constraint_system_from_reader(File::open(circuit_file).unwrap()).unwrap();
    let witness = noir_types::witness_from_reader(File::open(witness_file).unwrap()).unwrap();
    let mut driver = PlainAcvmSolver::new();

    let recursion_crs_size = constraint_system.get_honk_recursion_public_inputs_size::<Bn254G1>();
    let recursion_crs = if recursion_crs_size > 0 {
        CrsParser::<Bn254G1>::get_crs_g1(CRS_PATH_G1, recursion_crs_size, has_zk).unwrap()
    } else {
        ProverCrs::default()
    };
    let builder = UltraCircuitBuilder::<Bn254G1>::create_circuit(
        &constraint_system,
        0,
        witness,
        HonkRecursion::UltraHonk,
        &recursion_crs,
        &mut driver,
    )
    .unwrap();
    let crs_size = builder.compute_dyadic_size();
    let crs =
        CrsParser::<Bn254G1>::get_crs::<Bn254>(CRS_PATH_G1, CRS_PATH_G2, crs_size, has_zk).unwrap();
    let (prover_crs, verifier_crs) = crs.split();

    let (proving_key, verifying_key) = builder
        .create_keys::<Bn254>(prover_crs.into(), verifier_crs, &mut driver)
        .unwrap();

    // VK byte-KAT: the serialized VK must match the bb-generated bytes (KAT provenance
    // in the kat/ dir). bb VK bytes are zk-independent, so this holds in both modes.
    let vk_u8 = vk_to_buffer(&verifying_key.inner_vk);
    let read_vk_u8 = std::fs::read(vk_file).unwrap();
    assert_eq!(vk_u8, read_vk_u8);

    let (proof, public_inputs) =
        UltraHonk::<_, H>::prove(proving_key, has_zk, &verifying_key.inner_vk).unwrap();
    if has_zk == ZeroKnowledge::No {
        let proof_u8 = H::to_buffer(proof.inner_as_ref());
        let read_proof_u8 = std::fs::read(proof_file).unwrap();
        assert_eq!(proof_u8, read_proof_u8);

        let read_proof = HonkProof::new(H::from_buffer(&read_proof_u8));
        assert_eq!(proof, read_proof);
    }

    let mut extended = H::to_buffer(proof.inner_as_ref());
    extended.extend_from_slice(&[0u8; 32]);
    let extended = HonkProof::new(H::from_buffer(&extended));
    let rejected = UltraHonk::<_, H>::verify(extended, &public_inputs, &verifying_key, has_zk);
    assert!(rejected.is_err(), "proof with trailing data was accepted");

    let is_valid =
        UltraHonk::<_, H>::verify(proof, &public_inputs, &verifying_key, has_zk).unwrap();
    assert!(is_valid);
}

/// VK-only byte-KAT: build the circuit, derive keys, and assert the serialized VK matches the
/// bb-generated bytes — without proving. This pins the builder's full gate layout (the in-circuit
/// recursion verifier in particular), which proof KATs cannot do for recursion circuits: their
/// proof bytes are prover-specific (mask_points samples a random offset generator as a free
/// witness), so VK identity + cross-verification is the parity criterion there.
fn vk_kat_test(
    vk_file: &str,
    vk_to_buffer: fn(&VerifyingKeyBarretenberg<Bn254G1>) -> Vec<u8>,
    circuit_file: &str,
    witness_file: &str,
) {
    let constraint_system =
        constraint_system_from_reader(File::open(circuit_file).unwrap()).unwrap();
    let witness = noir_types::witness_from_reader(File::open(witness_file).unwrap()).unwrap();
    let mut driver = PlainAcvmSolver::new();

    let recursion_crs_size = constraint_system.get_honk_recursion_public_inputs_size::<Bn254G1>();
    let recursion_crs = if recursion_crs_size > 0 {
        CrsParser::<Bn254G1>::get_crs_g1(CRS_PATH_G1, recursion_crs_size, ZeroKnowledge::No)
            .unwrap()
    } else {
        ProverCrs::default()
    };
    let builder = UltraCircuitBuilder::<Bn254G1>::create_circuit(
        &constraint_system,
        0,
        witness,
        HonkRecursion::UltraHonk,
        &recursion_crs,
        &mut driver,
    )
    .unwrap();
    let crs_size = builder.compute_dyadic_size();
    let crs = CrsParser::<Bn254G1>::get_crs::<Bn254>(
        CRS_PATH_G1,
        CRS_PATH_G2,
        crs_size,
        ZeroKnowledge::No,
    )
    .unwrap();
    let (prover_crs, verifier_crs) = crs.split();

    let (_proving_key, verifying_key) = builder
        .create_keys::<Bn254>(prover_crs.into(), verifier_crs, &mut driver)
        .unwrap();

    let vk_u8 = vk_to_buffer(&verifying_key.inner_vk);
    let read_vk_u8 = std::fs::read(vk_file).unwrap();
    assert_eq!(vk_u8, read_vk_u8);
}

